const PROMPT = 'Три варіанти поєднуються з опорним словом, а один — дистрактор. Знайди зайве слово.'

const mk = (
  id: string,
  head: string,
  valid: [string, string][], // 3 collocates with notes
  intruder: [string, string], // the odd one out + note
  explain: string,
): Question => ({
  id,
  mode: 'oddone',
  prompt: PROMPT,
  sentence: head,
  options: [
    ...valid.map(([t, note]) => ({ t, ok: false, note })),
    { t: intruder[0], ok: true, note: intruder[1] },
  ],
  explain,
})

